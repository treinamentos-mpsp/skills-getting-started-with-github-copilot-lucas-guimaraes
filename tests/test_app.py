from copy import deepcopy

import pytest
from fastapi.testclient import TestClient

from src import app as api


BASE_ACTIVITIES = deepcopy(api.activities)


@pytest.fixture(autouse=True)
def reset_activities(monkeypatch):
    monkeypatch.setattr(api, "activities", deepcopy(BASE_ACTIVITIES))


@pytest.fixture
def client():
    with TestClient(api.app) as test_client:
        yield test_client


def test_get_activities_returns_activity_details(client):
    # Arrange
    activity_name = "Chess Club"

    # Act
    response = client.get("/activities")

    # Assert
    assert response.status_code == 200
    assert activity_name in response.json()
    assert response.json()[activity_name] == BASE_ACTIVITIES[activity_name]


def test_signup_adds_participant(client):
    # Arrange
    activity_name = "Chess Club"
    email = "new.student@mergington.edu"

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert response.json() == {
        "message": f"Signed up {email} for {activity_name}"
    }
    assert email in api.activities[activity_name]["participants"]


